#!/usr/bin/env python3
"""~/.claude/agents/*.md (Claude Code subagent) を pi-subagents の agent 定義に変換して
~/.pi/agent/agents/（引数で変更可）に書く。生成物は追跡しない。元を直したら再実行する。

本文はそのまま、frontmatter は行単位で読み替える（YAML パーサは持たない。`|` ブロック・
コメント・リストは pi-subagents 自身が解釈する）:
  model / color  → 削除。sonnet/haiku/opus/fable は pi では解決できない（OpenAI auth のみ）ので
                   default model を継承させる
  tools          → Read/Grep/Glob/Bash/Write/Edit を read/grep/find/bash/write/edit に。
                   Skill は read で代替され、WebSearch/WebFetch は pi core に無いので落とす。"*" は行ごと削除
  skills の項目  → "plugin:name" を "name" に（pi の skill 名に plugin 接頭辞は無い）
  追加           → advertise: true（subagent ツール有効時に親のプロンプトへ一覧を出す）

生成しないもの: git がリポジトリから除外している元ファイル（.git/info/exclude 等。非公開の agent）と、
EXCLUDE に挙げた pi では動かない agent。
"""

import re
import subprocess
import sys
from pathlib import Path

SRC = Path.home() / ".claude/agents"
DST = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / ".pi/agent/agents"
# claude.ai の Drive コネクタ前提で pi では動かず、本番の帳簿に書く
EXCLUDE = {"receipt-pipeline"}
TOOL = {"Read": "read", "Grep": "grep", "Glob": "find", "Bash": "bash", "Write": "write", "Edit": "edit"}


def git_excluded(path: Path) -> bool:
    """リポジトリが除外しているファイル（非公開）か。git 管理外なら False。
    ~/.claude は dotfiles への symlink なので realpath に直してから聞く（symlink 経由の絶対パスは worktree 外扱い）。"""
    real = path.resolve()
    try:
        result = subprocess.run(["git", "-C", str(real.parent), "check-ignore", "-q", str(real)], capture_output=True)
    except OSError:
        return False
    return result.returncode == 0


def split(text: str):
    m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.DOTALL)
    if not m:
        raise SystemExit(f"no frontmatter: {text[:40]!r}")
    return m.group(1), m.group(2)


def convert(front: str, src: Path) -> list[str]:
    out = [f"# generated by scripts/claude-agents-to-pi.py from {src} — edit the source, then re-run", "advertise: true"]
    in_skills = False
    for line in front.splitlines():
        top = re.match(r"^([A-Za-z_-]+):(.*)$", line)
        if top:
            key, val = top.group(1), top.group(2).strip()
            in_skills = key == "skills"
            if key in ("model", "color"):
                continue
            if key == "tools":
                if val.strip('"') != "*":
                    mapped = sorted({TOOL[t] for t in re.split(r",\s*", val) if t in TOOL})
                    if mapped:
                        out.append(f"tools: {', '.join(mapped)}")
                continue
        elif in_skills:
            line = re.sub(r"^(\s*-\s*)[\w-]+:([\w-]+)\s*$", r"\1\2", line)
        out.append(line)
    return out


if __name__ == "__main__":
    DST.mkdir(parents=True, exist_ok=True)
    for src in sorted(SRC.glob("*.md")):
        if src.stem in EXCLUDE or git_excluded(src):
            continue
        front, body = split(src.read_text())
        (DST / src.name).write_text("---\n" + "\n".join(convert(front, src)) + "\n---\n" + body)
        print(src.name)
